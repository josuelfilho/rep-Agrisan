/* NOTAS DE COMPRA COM FRETE x CT-e VINCULADO (BASE DA LISTA PRINCIPAL DO PAINEL NF x CT-e)
   MESMA CONSULTA MONTADA EM SQL.nfs NO index.jsp. PARA TESTAR NO DBEXPLORER, AJUSTE O PERIODO.
   - NF: FILTROS APLICADOS UMA UNICA VEZ (DATA COM TO_DATE PARA USAR INDICE E NAO DEPENDER DO NLS)
   - VINC: VINCULO NF x CTE PELA TGFNCT EM UM UNICO JOIN (SEM SUBCONSULTA CORRELACIONADA POR LINHA)
   - RESUMO: QTD E VALOR DE CT-e POR NF (DISTINCT NA VINC EVITA SOMAR O MESMO CT-e DUAS VEZES) */
WITH NF AS (
  SELECT /*+ MATERIALIZE */
         N.NUNOTA, N.NUMNOTA, N.SERIENOTA, N.CODEMP, N.CHAVENFE, N.DTNEG, N.DTENTSAI,
         N.CODNAT, N.CODCENCUS, N.CODPROJ, N.VLRNOTA, N.VLRFRETE, N.CODTIPOPER,
         N.STATUSNOTA, N.CODPARC, TPO.DESCROPER
    FROM TGFCAB N
   INNER JOIN TGFTOP TPO ON TPO.CODTIPOPER = N.CODTIPOPER AND TPO.DHALTER = N.DHTIPOPER
   WHERE N.TIPMOV = 'C'
     AND N.VLRFRETE <> 0
     AND NVL(TPO.CODMODDOC, 0) <> 57
     AND N.DTNEG >= TO_DATE('01/09/2026', 'DD/MM/YYYY')
     AND N.DTNEG <  TO_DATE('06/11/2026', 'DD/MM/YYYY') + 1
),
VINC AS (
  SELECT DISTINCT NF.NUNOTA AS NUNOTANF, CTE.NUNOTA AS NUNOTACTE, NVL(CTE.VLRNOTA, 0) AS VLRCTE
    FROM NF
   INNER JOIN TGFNCT NCT ON NCT.CHAVENFE = NF.CHAVENFE
   INNER JOIN TGFCAB CTE ON CTE.NUNOTA = NCT.NUNOTA AND CTE.TIPMOV = 'C'
   WHERE NF.CHAVENFE IS NOT NULL
     AND TO_NUMBER(NCT.NUMERO) = NF.NUMNOTA
),
RATCTE AS (                                            -- CT-e DO PERIODO QUE POSSUEM RATEIO
  SELECT RAV.NUFIN AS NUNOTACTE
    FROM (SELECT DISTINCT NUNOTACTE FROM VINC) V
   INNER JOIN TGFRAV RAV ON RAV.ORIGEM = 'E' AND RAV.NUFIN = V.NUNOTACTE
   GROUP BY RAV.NUFIN
),
RESUMO AS (
  SELECT V.NUNOTANF, COUNT(*) AS QTDCTE, SUM(V.VLRCTE) AS VLRCTE,
         SUM(CASE WHEN RC.NUNOTACTE IS NULL THEN 1 ELSE 0 END) AS QTDCTESEMRAT
    FROM VINC V
    LEFT JOIN RATCTE RC ON RC.NUNOTACTE = V.NUNOTACTE
   GROUP BY V.NUNOTANF
)
SELECT N.NUNOTA, N.NUMNOTA, N.SERIENOTA, N.CODEMP, N.CHAVENFE AS CHAVE,
       TO_CHAR(N.DTNEG, 'DD/MM/YYYY') AS DTNEG, TO_CHAR(N.DTENTSAI, 'DD/MM/YYYY') AS DTENTSAI,
       N.CODNAT, NAT.DESCRNAT, N.CODCENCUS, CUS.DESCRCENCUS, N.CODPROJ, PRJ.IDENTIFICACAO AS DESCRPROJ,
       N.VLRNOTA, NVL(N.VLRFRETE, 0) AS VLRFRETE, N.CODTIPOPER, N.DESCROPER,
       CASE WHEN N.STATUSNOTA = 'L' THEN 'Sim' ELSE 'Não' END AS CONFIRMADA,
       N.CODPARC, PAR.NOMEPARC,
       NVL(R.QTDCTE, 0) AS QTDCTE, NVL(R.VLRCTE, 0) AS VLRCTE, NVL(R.QTDCTESEMRAT, 0) AS QTDCTESEMRAT
  FROM NF N
  LEFT JOIN RESUMO R ON R.NUNOTANF = N.NUNOTA          -- "APENAS NF-e COM CT-e": TROCAR POR INNER JOIN
                                                       -- "COM CT-e SEM RATEIO": INNER JOIN + WHERE R.QTDCTESEMRAT > 0
 INNER JOIN TGFPAR PAR ON PAR.CODPARC = N.CODPARC
  LEFT JOIN TGFNAT NAT ON NAT.CODNAT = N.CODNAT
  LEFT JOIN TSICUS CUS ON CUS.CODCENCUS = N.CODCENCUS
  LEFT JOIN TCSPRJ PRJ ON PRJ.CODPROJ = N.CODPROJ
