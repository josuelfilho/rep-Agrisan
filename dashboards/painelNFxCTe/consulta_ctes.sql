/* CT-e DE ENTRADA x NF-e DE COMPRA (BASE DA LISTA PRINCIPAL DO PAINEL CT-e x NOTAS DE COMPRA)
   MESMA CONSULTA MONTADA EM SQL.ctes NO index.jsp. PARA TESTAR NO DBEXPLORER, AJUSTE O PERIODO.
   - CT:   CT-e DO PERIODO (TIPMOV 'C', TOP MODELO 57). DATA COM TO_DATE PARA USAR INDICE
   - VINC: NF-e VINCULADAS A CADA CT-e PELA TGFNCT EM UM UNICO JOIN (SEM SUBCONSULTA POR LINHA)
   - QNF:  QUANTIDADE DE NF-e POR CT-e
   - RAT:  QUANTIDADE DE LINHAS DE RATEIO (TGFRAV ORIGEM 'E') POR CT-e
   FILTRO OPCIONAL NA CTE "CT":
   - TOPs DO CT-e: AND N.CODTIPOPER IN (27)
   FILTROS OPCIONAIS NO FINAL:
   - TOPs DA NF-e: N.NUNOTA IN (SELECT V.NUNOTACTE FROM VINC V WHERE V.TOPNF IN (9, 26))
   - APENAS CT-e SEM RATEIO: R.NUNOTACTE IS NULL (NO PAINEL ESTE FILTRO E FEITO NA TELA, PELO TOTAL "CT-e SEM RATEIO") */
SELECT * FROM (
WITH CT AS (
  SELECT /*+ MATERIALIZE */
         N.NUNOTA, N.NUMNOTA, N.SERIENOTA, N.CODEMP, NVL(N.CHAVECTE, N.CHAVENFE) AS CHAVE, N.DTNEG, N.DTENTSAI,
         N.CODNAT, N.CODCENCUS, N.CODPROJ, N.VLRNOTA, N.CODTIPOPER, N.STATUSNOTA, N.CODPARC,
         N.TIPFRETE, N.CIF_FOB, TPO.DESCROPER
    FROM TGFCAB N
   INNER JOIN TGFTOP TPO ON TPO.CODTIPOPER = N.CODTIPOPER AND TPO.DHALTER = N.DHTIPOPER
   WHERE N.TIPMOV = 'C'
     AND TPO.CODMODDOC = 57
     AND N.DTENTSAI >= TO_DATE('01/11/2026', 'DD/MM/YYYY')
     AND N.DTENTSAI <  TO_DATE('11/11/2026', 'DD/MM/YYYY') + 1
),
VINC AS (
  SELECT DISTINCT C.NUNOTA AS NUNOTACTE, NF.NUNOTA AS NUNOTANF, NF.CODTIPOPER AS TOPNF
    FROM CT C
   INNER JOIN TGFNCT NCT ON NCT.NUNOTA = C.NUNOTA
   INNER JOIN TGFCAB NF ON NF.CHAVENFE = NCT.CHAVENFE AND NF.NUMNOTA = TO_NUMBER(NCT.NUMERO) AND NF.TIPMOV = 'C'
),
QNF AS (
  SELECT NUNOTACTE, COUNT(*) AS QTDNF FROM VINC GROUP BY NUNOTACTE
),
RAT AS (
  SELECT RAV.NUFIN AS NUNOTACTE, COUNT(*) AS QTDRAT
    FROM CT C
   INNER JOIN TGFRAV RAV ON RAV.ORIGEM = 'E' AND RAV.NUFIN = C.NUNOTA
   GROUP BY RAV.NUFIN
)
SELECT N.NUNOTA, N.NUMNOTA, N.SERIENOTA, N.CODEMP, EMP.NOMEFANTASIA, N.CHAVE,
       TO_CHAR(N.DTNEG, 'DD/MM/YYYY') AS DTNEG, TO_CHAR(N.DTENTSAI, 'DD/MM/YYYY') AS DTENTSAI,
       N.CODNAT, NAT.DESCRNAT, N.CODCENCUS, CUS.DESCRCENCUS, N.CODPROJ, PRJ.IDENTIFICACAO AS DESCRPROJ,
       N.VLRNOTA, NVL(Q.QTDNF, 0) AS QTDNF, NVL(R.QTDRAT, 0) AS QTDRAT,
       N.CODTIPOPER, N.DESCROPER,
       CASE WHEN N.STATUSNOTA = 'L' THEN 'Sim' ELSE 'Não' END AS CONFIRMADA,
       N.CODPARC, PAR.NOMEPARC,
       NVL(F_DESCROPC('TGFCAB', 'TIPFRETE', N.TIPFRETE), N.TIPFRETE) AS TIPFRETE,
       CASE WHEN N.CIF_FOB IS NULL OR N.CIF_FOB = 'S' THEN 'Não informado'
            ELSE NVL(F_DESCROPC('TGFCAB', 'CIF_FOB', N.CIF_FOB), N.CIF_FOB) END AS CIFFOB
  FROM CT N
  LEFT JOIN QNF Q ON Q.NUNOTACTE = N.NUNOTA
  LEFT JOIN RAT R ON R.NUNOTACTE = N.NUNOTA
 INNER JOIN TGFPAR PAR ON PAR.CODPARC = N.CODPARC
  LEFT JOIN TSIEMP EMP ON EMP.CODEMP = N.CODEMP
  LEFT JOIN TGFNAT NAT ON NAT.CODNAT = N.CODNAT
  LEFT JOIN TSICUS CUS ON CUS.CODCENCUS = N.CODCENCUS
  LEFT JOIN TCSPRJ PRJ ON PRJ.CODPROJ = N.CODPROJ
) X
WHERE ROWNUM <= 3001
